"""
Prediction Engine and Feature Interpretation Module.
Performs classification inference on incoming text, computes class probability/confidence scores,
and identifies the most indicative lexical terms contributing to the predicted legal category.
"""
import numpy as np
from typing import Dict, Any, List
from app.ml.preprocessor import clean_legal_text, legal_tokenizer
from app.ml.model_trainer import load_best_model_artifact


class PredictionService:
    def __init__(self):
        self.artifact = None
        self._load_model()

    def _load_model(self):
        self.artifact = load_best_model_artifact()

    def reload(self):
        self._load_model()

    def is_model_ready(self) -> bool:
        return self.artifact is not None and "pipeline" in self.artifact

    def predict(self, raw_text: str) -> Dict[str, Any]:
        """
        Executes inference and returns comprehensive classification diagnostics.
        """
        if not self.is_model_ready():
            self._load_model()
            if not self.is_model_ready():
                return {
                    "success": False,
                    "error": "No trained model found. Please train a model via the Dataset Explorer first."
                }

        cleaned = clean_legal_text(raw_text)
        tokens = legal_tokenizer(raw_text)

        # Minimum input validation
        if len(cleaned.strip()) < 20 or len(tokens) < 3:
            return {
                "success": False,
                "error": "Input text is too short or lacks sufficient legal content to classify reliably (minimum 20 characters and 3 words required)."
            }

        pipeline = self.artifact["pipeline"]
        model_name = self.artifact.get("model_name", "Unknown Classifier")
        classes = self.artifact.get("classes", [])

        # Predict category
        predicted_class = pipeline.predict([raw_text])[0]

        # Calculate probabilities or confidence scores
        confidence_available = False
        confidence_score = 0.0
        all_class_scores = []

        clf = pipeline.named_steps["clf"]
        tfidf = pipeline.named_steps["tfidf"]

        if hasattr(pipeline, "predict_proba"):
            try:
                probs = pipeline.predict_proba([raw_text])[0]
                confidence_available = True
                pred_idx = list(classes).index(predicted_class) if predicted_class in classes else np.argmax(probs)
                confidence_score = round(float(probs[pred_idx]), 4)

                for cls_name, prob in zip(classes, probs):
                    all_class_scores.append({
                        "category": str(cls_name),
                        "score": round(float(prob) * 100, 2),
                        "score_type": "Calibrated Probability (%)"
                    })
                all_class_scores.sort(key=lambda x: x["score"], reverse=True)
            except Exception as e:
                confidence_available = False

        # Extract top indicative terms contributing to the prediction
        indicative_terms = self._extract_indicative_terms(
            raw_text, predicted_class, tfidf, clf, classes
        )

        return {
            "success": True,
            "predicted_category": str(predicted_class),
            "model_used": model_name,
            "confidence_available": confidence_available,
            "confidence_score_percent": round(confidence_score * 100, 1) if confidence_available else None,
            "all_class_scores": all_class_scores,
            "indicative_terms": indicative_terms,
            "text_statistics": {
                "raw_char_count": len(raw_text),
                "token_count": len(tokens),
                "unique_token_count": len(set(tokens))
            },
            "disclaimer": (
                "Educational Classification Tool Notice: This prediction is generated by statistical machine learning "
                "models for academic demonstration and does not constitute legal counsel or evaluate legal validity."
            )
        }

    def _extract_indicative_terms(self, text: str, predicted_class: str, tfidf, clf, classes) -> List[Dict[str, Any]]:
        """
        Identifies terms present in the document that have the strongest positive association
        with the predicted category based on model weights or log probabilities.
        """
        try:
            # Vectorize document
            doc_vec = tfidf.transform([text])
            feature_names = np.array(tfidf.get_feature_names_out())
            nonzero_indices = doc_vec.nonzero()[1]

            if len(nonzero_indices) == 0:
                return []

            class_idx = list(classes).index(predicted_class) if predicted_class in classes else 0

            # Inspect model weights
            weights = None
            if hasattr(clf, "coef_"):
                # Multi-class Logistic Regression
                if clf.coef_.ndim == 2:
                    weights = clf.coef_[class_idx]
                else:
                    weights = clf.coef_
            elif hasattr(clf, "feature_log_prob_"):
                # Multinomial Naive Bayes: log prob for this class minus average across all classes
                class_log_prob = clf.feature_log_prob_[class_idx]
                mean_other_log_prob = np.mean(
                    [clf.feature_log_prob_[i] for i in range(len(classes)) if i != class_idx],
                    axis=0
                ) if len(classes) > 1 else class_log_prob
                weights = class_log_prob - mean_other_log_prob
            elif hasattr(clf, "calibrated_classifiers_"):
                # CalibratedClassifierCV: Average weights across calibrated estimators if linear
                coef_list = []
                for cc in clf.calibrated_classifiers_:
                    base_est = getattr(cc, "estimator", getattr(cc, "base_estimator", None))
                    if hasattr(base_est, "coef_"):
                        coef = base_est.coef_
                        if coef.ndim == 2:
                            coef_list.append(coef[class_idx])
                        else:
                            coef_list.append(coef)
                if coef_list:
                    weights = np.mean(coef_list, axis=0)

            if weights is not None:
                # Get weights for tokens occurring in this document
                token_weights = []
                for idx in nonzero_indices:
                    term = feature_names[idx]
                    w = float(weights[idx])
                    tf_val = float(doc_vec[0, idx])
                    # Combined impact score = TF-IDF * feature weight
                    impact = w * tf_val
                    token_weights.append((term, impact, w))

                # Sort by impact descending
                token_weights.sort(key=lambda x: x[1], reverse=True)
                top_terms = [
                    {"term": t[0], "weight": round(t[1], 4)}
                    for t in token_weights[:8] if t[1] > 0
                ]
                return top_terms

            # Fallback: Top TF-IDF tokens in document
            token_scores = [(feature_names[i], float(doc_vec[0, i])) for i in nonzero_indices]
            token_scores.sort(key=lambda x: x[1], reverse=True)
            return [{"term": t[0], "weight": round(t[1], 4)} for t in token_scores[:8]]

        except Exception as e:
            return []


# Global singleton instance
predictor_service = PredictionService()
